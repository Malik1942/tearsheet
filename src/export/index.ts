import type { Resolved } from '../lib/mapRelations'
import type { Brick } from '../lib/types'
import { PARAMETER_KEYS, RELATIONSHIP_KEYS, SKIN_KEYS, toCssVars } from '../shell/params'

export function exportJson(intent: string, r: Resolved): string {
  return JSON.stringify({ intent, parameters: r.values, unexpressed: r.unexpressed }, null, 2)
}

export function exportCss(r: Resolved): string {
  const vars = toCssVars(r.params)
  const lines = PARAMETER_KEYS.map(k => `  --${k.replace(/_/g, '-')}: ${JSON.stringify(String(r.params[k])).replace(/^"|"$/g, '')}; /* ${r.values[k].provenance} */`)
  const derived = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`)
  return `:root {\n${lines.join('\n')}\n\n  /* resolved shell variables */\n${derived.join('\n')}\n}\n`
}

export function exportHandoff(intent: string, bricks: Brick[], r: Resolved): string {
  const chosen = RELATIONSHIP_KEYS.filter(k => r.values[k].provenance !== 'adapted')
  const lines: string[] = [
    `# Handoff: ${intent}`, '',
    `Generated by Tearsheet on ${new Date().toISOString().slice(0, 10)}. Every parameter below says where it came from: measured (read off a reference photo), interpreted (a hypothesis or a hand remap), adapted (the shell's own default).`, '',
    '## References', '',
    ...bricks.map(b => `- **${b.id}** saved ${b.saved_at}: ![${b.id}](${b.photo.url}) ${b.photo.width}x${b.photo.height}. Fragile if changed: ${b.fragile_if_changed}`), '',
    '## Keep these relations', '',
    ...chosen.map(k => { const v = r.values[k]; return `- \`${k}\` = **${v.value}** (${v.provenance}${v.source?.brickId ? `, from ${v.source.brickId}` : ''})${v.source?.relationRule ? `: ${v.source.relationRule}` : ''}${v.locked ? ' [locked]' : ''}` }), '',
    '## Appearance', '',
    ...SKIN_KEYS.map(k => `- \`${k}\` = ${r.values[k].value} (${r.values[k].provenance})`), '',
    '## Could not be expressed', '',
    ...(r.unexpressed.length ? r.unexpressed.map(u => `- [${u.brickId}, ${u.reason}] ${u.rule}`) : ['- nothing']), '',
    '## Instructions for a coding agent', '',
    'Apply the variables in `tokens.css` as-is. Keep the relations listed under "Keep these relations"; they are the character of the references, and a locked one is not negotiable. The features under "Could not be expressed" need design judgment: no token carries them, so decide explicitly whether and how to honor each, and say so in your notes.', '',
  ]
  return lines.join('\n')
}

export function download(name: string, text: string, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = Object.assign(document.createElement('a'), { href: url, download: name })
  a.click()
  URL.revokeObjectURL(url)
}
