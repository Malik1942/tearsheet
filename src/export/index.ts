import type { Proposal, Resolved } from '../lib/mapRelations'
import type { Brick } from '../lib/types'
import { footnoteOf, isShellDefault, rowHeadline } from '../lib/landing'
import { standInLine } from '../lib/standIns'
import { PARAMETER_KEYS, RELATIONSHIP_KEYS, SKIN_KEYS, toCssVars } from '../shell/params'

const origin = (r: Resolved, k: (typeof PARAMETER_KEYS)[number]) => {
  const v = r.values[k]; const s = v.source
  if (v.provenance === 'adapted' && !s?.measurementIds?.length && !s?.note?.startsWith('by')) return 'adapted · shell default'
  const bits = [v.provenance, s?.brickId && s.brickId !== 'user' ? s.brickId : '', s?.relationId ?? '', s?.measurementIds?.length ? `from ${s.measurementIds.join(', ')}` : '', s?.note?.startsWith('by') ? s.note.split(':')[0] : '']
  return bits.filter(Boolean).join(' · ')
}

export function exportJson(intent: string, r: Resolved, proposal?: Proposal, brickIds?: string[]): string {
  return JSON.stringify({ intent, brickIds: brickIds ?? null, proposal: proposal ?? null, parameters: r.values, conflicts: r.conflicts, capped: r.capped.map(c => ({ ref: c.ref, key: c.key, value: c.value })), unexpressed: r.unexpressed }, null, 2)
}

/** Custom properties for the skin and the relationship switches, one comment per value in the order of the sheet (C4′): the rule and where it lands, then its source, then the measurement.
 *  A shell default is its headline alone (`Shell default → …`): the origin would only say it again. Where those texts would close a comment they are broken to `* /`, so a comment never closes early. Plus the resolved shell variables. */
export function exportCss(r: Resolved, bricks: Brick[]): string {
  const vars = toCssVars(r.params)
  const lines = PARAMETER_KEYS.map(k => {
    const comment = [rowHeadline(r.values[k], r.params, bricks), isShellDefault(r.values[k]) ? '' : origin(r, k), footnoteOf(r.values[k], bricks)].filter(Boolean).join(' · ')
    return `  --${k.replace(/_/g, '-')}: ${cssValue(String(r.params[k]))}; /* ${comment.replaceAll('*/', '* /')} */`
  })
  const derived = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`)
  return `/* Tearsheet tokens. Relationship parameters are layout switches; read them in JS or map them to data-* attributes (see shell/params.ts dataAttributes). */\n:root {\n${lines.join('\n')}\n\n  /* resolved shell variables, what the two reference screens actually consume */\n${derived.join('\n')}\n}\n`
}

/** A CSS custom property value may hold almost anything, but a bare "<=5%" or a family list with quotes must stay valid when read back. */
function cssValue(v: string): string {
  return /^[\w#.%-]+$/.test(v) ? v : /^".*"$/.test(v) || /,/.test(v) ? v : `"${v.replace(/"/g, '\\"')}"`
}

/** `photos: 'inline'` keeps data URLs in the image links so the same text renders as a page with thumbnails; the download stands them in. */
export function exportHandoff(intent: string, bricks: Brick[], r: Resolved, proposal?: Proposal, opts: { photos?: 'stub' | 'inline' } = {}): string {
  const kept = RELATIONSHIP_KEYS.filter(k => r.values[k].provenance !== 'adapted' || r.values[k].source?.note?.startsWith('by'))
  const photo = (b: Brick) => (b.photo.url.startsWith('data:') && opts.photos !== 'inline' ? '(embedded photo)' : b.photo.url)
  const howPicked = (b: Brick) => {
    const p = proposal?.picks.find(x => x.brickId === b.id)
    if (!p) return proposal ? ' Added by you.' : ''
    return p.status === 'proposed' ? ` Proposed by the model (${proposal!.model}, effort ${proposal!.effort}) for this intent, quoting its rule: "${p.quotedRule}" (${p.why})` : ` Swapped in by you for ${p.swappedFrom}.`
  }
  const lines: string[] = [
    `# Handoff: ${intent}`, '',
    `Generated by Tearsheet on ${new Date().toISOString().slice(0, 10)}. Every parameter below says where it came from: measured (read off a reference photo by the model in one run; another run may differ), interpreted (a hypothesis or a hand remap), adapted (set by a person or by the shell). Keep the provenance in your notes.`, '',
    proposedLine(bricks, proposal), '',
    '## Bricks used', '',
    ...bricks.map(b => `- **${b.id}** saved ${b.saved_at}${b.prompt_version ? `, prompt ${b.prompt_version}` : ''}: ![${b.id}](${photo(b)}) ${b.photo.width}x${b.photo.height}. Fragile if changed: ${b.fragile_if_changed}${howPicked(b)}`), '',
    '## Parameters and where each came from', '',
    ...PARAMETER_KEYS.map(k => { const v = r.values[k]; return `- \`${k}\` = **${v.value}** · ${origin(r, k)}${v.source?.relationRule ? `\n  - rule: ${v.source.relationRule}` : ''}${v.source?.note ? `\n  - note: ${v.source.note}` : ''}` }), '',
    '## Keep these relations', '',
    ...(kept.length ? kept.map(k => `- \`${k}\` = ${r.values[k].value}${r.values[k].locked ? ' [locked]' : ''}`) : ['- none beyond the shell defaults']), '',
    '## Conflicts and what was chosen', '',
    ...(r.conflicts.length ? r.conflicts.map(k => { const v = r.values[k]; const cands = (r.candidates[k] ?? []).map(c => `${c.ref} = ${c.value} (${c.provenance})`).join(', '); return `- \`${k}\`: ${cands}. ${v.source?.note?.startsWith('by you') ? v.source.note : 'Using the top brick; nobody chose.'}` }) : ['- none']), '',
    '## Switched off by the cap of three per brick', '',
    ...(r.capped.length ? r.capped.map(c => `- ${c.ref}: \`${c.key}\` = ${c.value}`) : ['- none']), '',
    '## Could not be expressed', '',
    ...(r.unexpressed.length ? r.unexpressed.flatMap(u => [`- [${u.brickId}, ${u.reason === 'fragile' ? 'fragile if changed' : 'no slot'}] ${u.rule}`, `  - ${standInLine(u.rule)}`]) : ['- Everything from these bricks found a slot.']), '',
    '## Appearance', '',
    ...SKIN_KEYS.map(k => `- \`${k}\` = ${r.values[k].value} · ${origin(r, k)}`), '',
    '## Instructions for a coding agent', '',
    'Apply the variables in `tokens.css` as-is. Keep the relations listed under "Keep these relations"; they are the character of the references, and a locked one is not negotiable. The features under "Could not be expressed" need design judgment: no token carries them, so decide explicitly whether and how to honor each, and say so in your notes. Do not invent provenance: anything you add is adapted.', '',
  ]
  return lines.join('\n')
}

/** How the current bricks got into the project. Only picks still `proposed` and still in the project count as the model's. */
export function proposedNow(brickIds: string[], proposal?: Proposal): number {
  const ids = new Set(brickIds)
  return proposal ? proposal.picks.filter(p => p.status === 'proposed' && ids.has(p.brickId)).length : 0
}

function proposedLine(bricks: Brick[], proposal?: Proposal): string {
  const n = proposedNow(bricks.map(b => b.id), proposal)
  if (!proposal || n === 0) return 'The bricks were chosen by a person; none of them is a model proposal.'
  return `${n} of ${bricks.length} bricks were proposed by the model from the library's rules on ${proposal.at.slice(0, 10)} (one text call with ids, rule text and parameters only; no photos) and accepted by a person; each such proposal quotes one rule of its brick verbatim, checked on the server before it was shown. The other bricks were chosen by the person.${proposal.dropped ? ` ${proposal.dropped} ${proposal.dropped === 1 ? 'pick was' : 'picks were'} dropped by that check.` : ''}`
}

export function download(name: string, text: string, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = Object.assign(document.createElement('a'), { href: url, download: name })
  a.click()
  URL.revokeObjectURL(url)
}
